/**
 * Generates server/services/cro03/sfp-premium-drafts.generated.ts from Appendix B (25 SFP drafts) and Appendix C
 * (warm/service baseline) of the Stage 4C1 specification. Pure file transform: no database, network or provider.
 *
 *   npx tsx scripts/generate-stage4c1-drafts.ts           write the module
 *   npx tsx scripts/generate-stage4c1-drafts.ts --check   exit 1 if the committed module differs from the source
 */
import { readFileSync, writeFileSync } from "node:fs";

export const SPEC_PATH = "attached_assets/Liberty-Stage4C1-Master-Preflight-and-Build-2026-10-31_1793469717746.md";
export const OUT_PATH = "server/services/cro03/sfp-premium-drafts.generated.ts";

const CTA_BY_LABEL: Record<string, string> = { "reply": "reply", "secure upload": "secure_statement_upload", "sales booking": "sales_booking" };

export function parse(md: string) {
  const lines = md.split("\n");
  const start = lines.findIndex((l) => l.startsWith("## Appendix B."));
  const end = lines.findIndex((l) => l.startsWith("## Appendix C."));
  if (start < 0 || end < 0) throw new Error("Appendix B/C not found");
  const sfp: Array<{ family: string; vertical: string; touch: number; day: number; cta: string; subject: string; body: string }> = [];
  let family = "", vertical = "";
  let cur: (typeof sfp)[number] | null = null;
  const buf: string[] = [];
  const flush = () => { if (cur) { cur.body = buf.join("\n").trim(); sfp.push(cur); } cur = null; buf.length = 0; };
  for (const line of lines.slice(start, end)) {
    const h = /^### B\d+\. (.+?) — `([a-z0-9_.]+)`/.exec(line);
    if (h) { flush(); vertical = h[1]; family = h[2]; continue; }
    const t = /^\*\*(\d) · Day(\d+) · (.+?) · Subject: (.+)\*\*$/.exec(line);
    if (t) {
      flush();
      const cta = CTA_BY_LABEL[t[3].toLowerCase()];
      if (!cta) throw new Error(`Unknown CTA label ${t[3]}`);
      cur = { family, vertical, touch: Number(t[1]), day: Number(t[2]), cta, subject: t[4], body: "" };
      continue;
    }
    if (cur) buf.push(line);
  }
  flush();

  const baseline: Array<{ use: string; subject: string | null; body: string; requirement: string }> = [];
  for (const line of lines.slice(end)) {
    if (!line.startsWith("| ") || line.startsWith("| ---") || line.startsWith("| Use /")) continue;
    const cells = line.replace(/^\| /, "").replace(/ \|$/, "").split(" | ");
    if (cells.length !== 3) throw new Error(`Appendix C row has ${cells.length} cells: ${line.slice(0, 60)}`);
    const [useSubject, body, requirement] = cells;
    const [use, subject] = useSubject.includes(" / ") ? [useSubject.split(" / ")[0], useSubject.split(" / ").slice(1).join(" / ")] : [useSubject, null];
    baseline.push({ use, subject, body: body.replace(/\\n/g, "\n"), requirement });
  }
  return { sfp, baseline };
}

export function render(md: string): string {
  const { sfp, baseline } = parse(md);
  return `/* GENERATED by scripts/generate-stage4c1-drafts.ts from the Stage 4C1 specification (Appendix B and C). Do not edit by hand. */
import type { CtaKind } from "../message-cta-contract";

/**
 * Proposed wording only. Nothing here is live, enrolled, activated or sent. CTA markers ([secure_statement_upload],
 * [sales_booking]) are resolved by the typed CTA contract at render time; they are never final hrefs.
 */
export interface PremiumSfpDraft {
  family: string; vertical: string; touch: number; day: number; cta: Extract<CtaKind, "reply" | "secure_statement_upload" | "sales_booking">;
  subject: string; body: string;
}
export interface WarmServiceBaseline { use: string; subject: string | null; body: string; requirement: string }

export const PREMIUM_SFP_DRAFTS: readonly PremiumSfpDraft[] = ${JSON.stringify(sfp, null, 2)} as const;

export const WARM_SERVICE_BASELINE: readonly WarmServiceBaseline[] = ${JSON.stringify(baseline, null, 2)} as const;
`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const out = render(readFileSync(SPEC_PATH, "utf8"));
  if (process.argv.includes("--check")) {
    const current = readFileSync(OUT_PATH, "utf8");
    if (current !== out) { console.error("DRIFT: generated drafts differ from the specification"); process.exit(1); }
    console.log("Generated drafts match the specification");
  } else {
    writeFileSync(OUT_PATH, out);
    console.log(`Wrote ${OUT_PATH}`);
  }
}
